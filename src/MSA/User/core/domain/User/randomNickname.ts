// 회원이 직접 정하는 닉네임 최대 글자 수 (숫자가 붙은 기본 닉네임은 넘을 수 있음)
export const NICKNAME_MAX_LENGTH = 6;

const pickOne =<T>(arr: readonly T[]): T =>
  arr[Math.floor(Math.random() * arr.length)];

/**
 * 아직 쓰이지 않은 후보 중 하나를 랜덤으로 고른다.
 * 숫자 없는 후보부터 쓰고, 다 쓰면 2, 3, … 순서로 숫자를 붙인다(예: 졸린수달2).
 * 고른 값은 used에 추가된다.
 */
export function pickRandomNickname(used: Set<string>): string {
  for (let suffix = 1; ; suffix++) {
    const available = RANDOM_NICKNAME_POOL.map((n) =>
      suffix === 1 ? n : `${n}${suffix}`,
    ).filter((n) => !used.has(n));
    if (available.length === 0) continue;
    const nickname = pickOne(available);
    used.add(nickname);
    return nickname;
  }
}
